export type TranslationKey = keyof typeof translations.ar

export function t(locale: Locale, key: TranslationKey): string {
  return (translations[locale] as Record<string, string>)[key] ?? (translations.ar as Record<string, string>)[key] ?? key
}

/** Hook-friendly shorthand — use inside components that already have locale */
export function createT(locale: Locale) {
  return (key: TranslationKey) => t(locale, key)
}
